"""Regenerate the source-derived HTTP and transaction inventory (no application startup)."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = root / 'src/main/java/org/misha/authservice'
rows = []
for file in sorted((source / 'controller').glob('*.java')):
    text = file.read_text(encoding='utf-8-sig')
    base = re.search(r'@RequestMapping\("([^"]+)"\)', text).group(1)
    for match in re.finditer(r'@(Get|Post|Put|Patch|Delete)Mapping(?:\((.*?)\))?\s*(.*?)public\s+([^\n]+?)\s+(\w+)\s*\(', text, re.S):
        verb, mapping, annotations, returned, name = match.groups()
        if 'public' in annotations or len(annotations) > 500:
            raise RuntimeError(f'Unrecognized mapping in {file.name}')
        mapping = mapping or ''
        paths = re.findall(r'"([^"]*)"', mapping.split('produces')[0]) or ['']
        signature = text[match.end():text.index('{', match.end())]
        body = text[text.index('{', match.end()):]
        # Stop at the next mapping; sufficient for this source's simple controller methods.
        body = re.split(r'@(?:Get|Post|Put|Patch|Delete)Mapping', body, maxsplit=1)[0]
        service_calls = re.findall(r'\b(\w+(?:Service|Resolver|Facade|Repository)|service|idempotency|availabilityService)\.(\w+)\(', body)
        calls = ', '.join(dict.fromkeys(f'{owner}.{method}' for owner, method in service_calls))
        success = '204' if 'ResponseEntity.noContent(' in body else '201' if 'HttpStatus.CREATED' in body else '200'
        signature = re.sub(r'\s+', ' ', signature).strip()
        for suffix in paths:
            path = base + suffix
            if path.startswith('/api/auth/'):
                matrix = ('yes', 'yes', 'yes', 'yes')
            elif path == '/api/profile/me':
                matrix = ('401', 'yes*', 'yes', 'yes')
            elif path.startswith('/api/v1/admin/sync/'):
                matrix = ('401', '403', 'yes**', 'yes**')
            else:
                matrix = ('401', '403', '403', 'yes')
            validation = 'Bean Validation' if '@Valid' in signature else 'service/manual; no @Valid'
            rows.append((verb.upper(), path, *matrix, file.stem + '.' + name, returned.strip(), validation, calls or 'see source', success, signature))

out = ['# HTTP inventory and access matrix', '',
       'Generated by `python scripts/audit_inventory.py` from controller source and reviewed against SecurityConfig. '
       'CLIENT does not exist in Role.java; its column describes a hypothetical authenticated ROLE_CLIENT. '
       '`yes*` = authenticated profile only; `yes**` = product/order additionally require approved API-key ownership or ADMIN traderId selection. '
       'Category sync is shared. OPTIONS is permitted for CORS. No `/api/v1/auth` controller or GET refresh exists.', '',
       'Successful status codes are listed per handler. Profile additionally returns 400/404. Shared errors preserve ApiError '
       '`code,message,status,timestamp`: validation/invalid input 400; authentication 401; authorization 403; '
       'not found 404; data/revision/idempotency conflicts 409; oversized multipart 413; unexpected failure 500. '
       'HTTP filter errors use the existing sendError contract. ResponseEntity<?> is intentionally shown as declared; '
       'inspect the linked controller for its dynamic payload. Transaction boundaries follow below.', '',
       '| Method | Path | Anonymous | CLIENT | TRADER | ADMIN | Handler | Declared response | Validation | Use case / side effects | Success |',
       '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
for row in rows:
    out.append('| ' + ' | '.join(str(v).replace('|', '\\|') for v in row[:-1]) + ' |')
out.extend(['', f'{len(rows)} mapped paths. API version names express historical contracts, not different privilege levels.', '',
            '## Request contracts', '', '| Handler | Parameters / request DTOs |', '| --- | --- |'])
for row in rows:
    out.append(f'| {row[6]} | `{row[-1].replace("|", " / ")}` |')
out.extend(['', '## Transaction inventory', '',
            'Source declarations only: proxy entry points join REQUIRED by default; self-invocation does not open another transaction. '
            'Outer ContractService/SyncService/IdempotencyService boundaries own critical use cases. '
            'RentalWriteLock requires an existing transaction; pullSync uses REPEATABLE_READ read-only.', '',
            '| Service | Annotation / following declaration |', '| --- | --- |'])
for file in sorted((source / 'service').glob('*.java')):
    text = file.read_text(encoding='utf-8-sig')
    for match in re.finditer(r'@Transactional(?:\([^\n]*\))?[^\n]*\n\s*public[^\n]+', text):
        declaration = re.sub(r'\s+', ' ', match.group()).replace('|', '\\|')
        out.append(f'| {file.stem} | `{declaration}` |')
(root / 'docs/audit/API_INVENTORY.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'Inventoried {len(rows)} HTTP paths')
